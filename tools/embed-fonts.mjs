// Regenerates src/invoice/fonts.ts: Yekan + B Titr as base64 data-URI @font-face rules (embedded inside the bundle itself).
// Usage: node tools/embed-fonts.mjs      (run only when public/invoice/Yekan.woff2 or BTitr.woff2 change)
import { readFile, writeFile } from "node:fs/promises";

const faces = [
  { family: "DY Yekan Emb", file: "public/invoice/Yekan.woff2" },
  { family: "DY Titr Emb", file: "public/invoice/BTitr.woff2" },
];
const rules = [];
for (const f of faces) {
  const b64 = (await readFile(new URL("../" + f.file, import.meta.url))).toString("base64");
  rules.push(`@font-face{font-family:"${f.family}";src:url(data:font/woff2;base64,${b64}) format("woff2");font-weight:100 900;font-style:normal;font-display:block}`);
}
const out =
  "/** GENERATED by tools/embed-fonts.mjs — do not edit. Yekan + B Titr embedded as data URIs (fallback if the extension-URL fonts of invoice/font.css are blocked). */\n" +
  "export const EMBEDDED_FONTS_CSS = " + JSON.stringify(rules.join("\n")) + ";\n";
await writeFile(new URL("../src/invoice/fonts.ts", import.meta.url), out);
console.log("src/invoice/fonts.ts written,", out.length, "bytes");
